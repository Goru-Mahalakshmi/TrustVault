"""Write the PostgreSQL schema (DDL) to db/schema.sql. The app creates the same schema itself via scripts/init_db.py;
this file is for reading and for review. A test fails if it is stale.   python -m scripts.export_schema"""
import pathlib
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from src.db.base import Base
import src.models  # noqa: F401

def render() -> str:
    d = postgresql.dialect()
    out = ["-- TrustVault schema (PostgreSQL). Generated by scripts/export_schema.py from the SQLAlchemy models.",
           "-- Apply with scripts/init_db.py (it also applies db/hardening.sql: grants + the audit immutability trigger).", ""]
    for t in Base.metadata.sorted_tables:
        out.append("\n".join(line.rstrip() for line in str(CreateTable(t).compile(dialect=d)).strip().splitlines()) + ";")
        out += ["\n".join(line.rstrip() for line in str(CreateIndex(i).compile(dialect=d)).strip().splitlines()) + ";" for i in sorted(t.indexes, key=lambda i: i.name)]
        out.append("")
    return "\n".join(line.rstrip() for line in out).rstrip() + "\n"

if __name__ == "__main__":
    pathlib.Path("db/schema.sql").write_text(render(), encoding="utf-8"); print("db/schema.sql written")
